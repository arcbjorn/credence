package main

import (
	"encoding/json"
	"fmt"
	"os"

	"github.com/arcbjorn/credence/gateway/canonical"
)

type vector struct {
	Name    string `json:"name"`
	Value   any    `json:"value"`
	Encoded string `json:"encoded"`
	Sha256  string `json:"sha256"`
}

func main() {
	ctrl := "line" + string(rune(1)) + "break"
	vs := []vector{
		{Name: "empty object", Value: map[string]any{}},
		{Name: "key ordering is byte-wise not insertion",
			Value: map[string]any{"zebra": 1, "apple": 2, "Zebra": 3}},
		{Name: "amounts are decimal strings never numbers",
			Value: map[string]any{"principal": "5000000000", "interest": "16438357"}},
		{Name: "nested objects sort at every level",
			Value: map[string]any{"b": map[string]any{"y": 1, "x": 2}, "a": 3}},
		{Name: "arrays preserve order",
			Value: map[string]any{"events": []any{3, 1, 2}}},
		{Name: "control characters escape as u00xx",
			Value: map[string]any{"note": ctrl}},
		{Name: "non-ascii is not escaped",
			Value: map[string]any{"label": "café"}},
		{Name: "u128 beyond float64 precision survives",
			Value: map[string]any{"amount": "340282366920938463463374607431768211455"}},
		{Name: "booleans and null",
			Value: map[string]any{"ok": true, "off": false, "missing": nil}},
	}
	for i := range vs {
		enc, err := canonical.Encode(vs[i].Value)
		if err != nil {
			panic(err)
		}
		h, _ := canonical.HashHex(vs[i].Value)
		vs[i].Encoded = string(enc)
		vs[i].Sha256 = h
	}
	out := map[string]any{
		"_comment": "Reference vectors for canonical encoding (docs/04). Go and Rust must both reproduce `encoded` and `sha256` byte for byte. Generated by gateway/internal/gen; do not hand-edit.",
		"vectors":  vs,
	}
	b, _ := json.MarshalIndent(out, "", "  ")
	os.WriteFile("../schemas/v1/canonical-vectors.json", append(b, '\n'), 0o644)
	fmt.Printf("wrote %d vectors\n", len(vs))
}
