/**
 * Environment and evidence modes, as `docs/09` requires them shown.
 *
 * > **Always show environment and evidence mode** in plain labels --
 * > `Scenario history`, `Observed account state`, `Development
 * > attestation`, `Deployed CRE policy checks`. **Never collapse these
 * > into an ambiguous green indicator.**
 *
 * That rule is the reason this file exists rather than a `status` string
 * with a colour attached. Each mode carries its own label and its own
 * visual treatment, and there is deliberately NO "ok" or "healthy"
 * variant for a component to fall back to: a reader must always be able to
 * tell scenario evidence from observed evidence, and a development
 * attestation from a CRE-delivered one.
 */

export type Origin = "Observed" | "Synthetic" | "Declared" | "Imported";
export type Route = "Development" | "CRE";

export interface Mode {
  /** The plain label. Shown verbatim; never abbreviated to an icon. */
  readonly label: string;
  /** CSS custom-property suffix, e.g. `--mode-scenario`. */
  readonly token: string;
  /** Why this label and not another. Surfaced in a tooltip/details. */
  readonly meaning: string;
}

/**
 * How one EVIDENCE ITEM was obtained.
 *
 * The labels name the origin and nothing else. Two of them used to name
 * an item type as well -- "Observed account state" and "Scenario
 * history" -- which read correctly on the account row and wrongly on the
 * other four: the evidence inspector renders one chip PER ITEM, so the
 * market, forecasts and portfolio rows were each captioned "account
 * state". Found by reading the built page, 21 September.
 */
export const EVIDENCE_MODES: Record<Origin, Mode> = {
  Observed: {
    label: "Observed",
    token: "observed",
    meaning:
      "Read from chain or a named provider at the recorded time. " +
      "This is the only origin that supports an executable claim.",
  },
  Synthetic: {
    label: "Synthetic",
    token: "scenario",
    meaning:
      "Generated by the simulation harness. `docs/04` caps any result " +
      "built on it at ScenarioOnly -- it cannot authorize a real action.",
  },
  Declared: {
    label: "Declared value",
    token: "declared",
    meaning:
      "Supplied by configuration rather than observed. Honest for a " +
      "fixed parameter, misleading if read as a measurement.",
  },
  Imported: {
    label: "Imported",
    token: "imported",
    meaning:
      "Brought in from outside this deployment. Accepted only by a " +
      "scenario facility.",
  },
};

export const ROUTE_MODES: Record<Route, Mode> = {
  Development: {
    label: "Development attestation",
    token: "development",
    meaning:
      "An assessment signed by the operator's key. One key pins routes " +
      "and allowlists signers -- honest for a prototype, not trustless.",
  },
  CRE: {
    label: "Deployed CRE policy checks",
    token: "cre",
    meaning:
      "A report delivered through the Keystone forwarder, authenticated " +
      "by transport rather than by signature.",
  },
};

/**
 * The authorization class, which is NOT a health indicator.
 *
 * `ScenarioOnly` is a correct, expected outcome for a scenario facility.
 * Rendering it as a warning would train a reader to read the demo's
 * normal state as a problem.
 */
export const CLASS_MODES: Record<string, Mode> = {
  Executable: {
    label: "Executable",
    token: "observed",
    meaning: "May authorize a real action on chain.",
  },
  PrototypeEligible: {
    label: "Prototype eligible",
    token: "development",
    meaning: "Executable within this prototype's trust model.",
  },
  ScenarioOnly: {
    label: "Scenario only",
    token: "scenario",
    meaning:
      "Built on synthetic evidence. Cannot authorize a real action, " +
      "by construction rather than by policy.",
  },
  Shadow: {
    label: "Shadow",
    token: "declared",
    meaning: "Computed and recorded, but authorizes nothing.",
  },
};

export function evidenceMode(origin: string): Mode {
  return (
    EVIDENCE_MODES[origin as Origin] ?? {
      label: `Unknown origin: ${origin}`,
      token: "unknown",
      meaning:
        "This origin is not one the interface knows. Shown verbatim " +
        "rather than guessed at.",
    }
  );
}

export function classMode(cls: string): Mode {
  return (
    CLASS_MODES[cls] ?? {
      label: cls,
      token: "unknown",
      meaning: "Class not recognized by the interface; shown verbatim.",
    }
  );
}
