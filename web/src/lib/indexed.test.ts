import { existsSync, readFileSync } from "node:fs";
import { resolve } from "node:path";
import { describe, expect, it } from "vitest";
import type { Indexed } from "./data";

/**
 * The indexed lifecycle, checked against what `docs/05` requires of loan
 * accounting.
 *
 * These assert the SHAPE and the ARITHMETIC of what the indexer stored,
 * not that a sync happened. `indexer/src/lifecycle.test.ts` already pins
 * the fold itself; this pins that what reached the bundle is consistent
 * with it — a fold that is right and an export that drops a field would
 * still put a wrong number on screen.
 *
 * Deliberately NOT guarded by `fixtureMissing`. Every other bundle file
 * is generated by the demos, which CI runs, so a missing one there is a
 * broken pipeline. This one needs Docker and a synced indexer, which CI
 * does not have, so its absence is expected rather than a failure. The
 * distinction matters: making this required would turn a green CI red
 * for a reason unrelated to the change being tested.
 */
const ROOT = resolve(process.cwd(), "..");
const INDEXED = `${ROOT}/web/public/data/indexed.json`;

describe.skipIf(!existsSync(INDEXED))("the indexed lifecycle", () => {
  const load = (): Indexed => JSON.parse(readFileSync(INDEXED, "utf8"));

  it("carries every amount as a string", () => {
    // uint256 through a JSON number is a silent precision loss, and a
    // ledger screen is exactly where that must not happen.
    for (const loan of load().loans) {
      expect(typeof loan.principal, `loan ${loan.loanId} principal`).toBe(
        "string",
      );
      expect(typeof loan.principalRepaid).toBe("string");
      expect(typeof loan.principalLoss).toBe("string");
    }
  });

  it("reconciles recovery and loss against the principal", () => {
    // `docs/05`: realized proceeds, principal loss and unpaid interest
    // must reconcile. For a resolved loan, what came back plus what was
    // written off is the whole principal -- the claim the screen prints
    // beside the figures.
    for (const loan of load().loans) {
      if (loan.status === "Active" || loan.status === "RecoveryPending") {
        continue;
      }
      const repaid = BigInt(loan.principalRepaid);
      const lost = BigInt(loan.principalLoss);
      expect(
        repaid + lost,
        `loan ${loan.loanId} (${loan.status}) does not reconcile`,
      ).toBe(BigInt(loan.principal));
    }
  });

  it("opens every loan before it resolves one", () => {
    const { loans, events } = load();
    for (const loan of loans) {
      const mine = events.filter((e) => e.loan_id === loan.id);
      expect(mine.length, `loan ${loan.loanId} has no events`).toBeGreaterThan(
        0,
      );
      expect(mine[0]?.kind, `loan ${loan.loanId} does not open`).toBe(
        "Originated",
      );
    }
  });

  it("keeps events in block order", () => {
    // The order IS the claim. A lifecycle presented out of order would
    // show recovery before origination and still look plausible.
    const { events } = load();
    for (let i = 1; i < events.length; i++) {
      const prev = events[i - 1]!;
      const cur = events[i]!;
      const prevKey = [BigInt(prev.blockNumber), prev.logIndex] as const;
      const curKey = [BigInt(cur.blockNumber), cur.logIndex] as const;
      const ordered =
        curKey[0] > prevKey[0] ||
        (curKey[0] === prevKey[0] && curKey[1] > prevKey[1]);
      expect(ordered, `event ${cur.id} is out of order after ${prev.id}`).toBe(
        true,
      );
    }
  });

  it("gives every event a distinct id and a transaction", () => {
    // Keyed on `<chain>-<block>-<logIndex>` rather than a tx hash,
    // because `collect` can emit Collected and Recovered in ONE
    // transaction. A duplicate id here means one of them was dropped.
    const { events } = load();
    const ids = new Set(events.map((e) => e.id));
    expect(ids.size, "duplicate event ids").toBe(events.length);
    for (const e of events) {
      expect(e.txHash, `event ${e.id} has no transaction`).toMatch(
        /^0x[0-9a-f]{64}$/,
      );
    }
  });

  it("resolves a terminal loan and leaves an open one unresolved", () => {
    for (const loan of load().loans) {
      const terminal = ["Repaid", "Recovered", "Defaulted"].includes(
        loan.status,
      );
      if (terminal) {
        expect(loan.resolvedAt, `${loan.status} loan has no resolvedAt`).toBeTruthy();
        expect(loan.heldSeconds, `${loan.status} loan has no heldSeconds`).toBeTruthy();
      } else {
        expect(loan.resolvedAt, "an open loan claims a resolution").toBeFalsy();
      }
    }
  });
});
